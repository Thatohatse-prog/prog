    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
// Get the customer name and selected product.
String customer = jTextField1.getText();
String product = jComboBox1.getSelectedItem().toString();

// Get the product price.
double price = Double.parseDouble(jTextField2.getText());

// Create the calculation object.
ProductCalculations calculation = new ProductCalculations(price);

// Calculate VAT, commission and total.
double vat = calculation.GetVat();
double commission = calculation.GetCommission();
double total = calculation.GetTotal();

// Display the sales information.
javax.swing.JOptionPane.showMessageDialog(this,
    "Customer Name: " + customer
    + "\nProduct: " + product
    + "\nVAT: R " + vat
    + "\nCOMMISSION: R " + commission
    + "\nTOTAL: R " + total
);try {
    java.io.FileWriter writer =
        new java.io.FileWriter("data.txt", true);

    writer.write("DATA LOG\n");
    writer.write("**************************************************\n");
    writer.write("Customer Name: " + customer + "\n");
    writer.write("Product: " + product + "\n");
    writer.write("VAT: R " + vat + "\n");
    writer.write("COMMISSION: R " + commission + "\n");
    writer.write("TOTAL: R " + total + "\n");
    writer.write("**************************************************\n");

    writer.close();

} catch (java.io.IOException e) {
    javax.swing.JOptionPane.showMessageDialog(this,
        "Error saving file.");
}        // TODO add your handling code here:
    }//GEN-LAST:event_jButton1ActionPerformed

